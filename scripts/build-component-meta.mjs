#!/usr/bin/env node
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const contractsDir = join(root, 'design/contracts/components');
const outputPath = join(root, 'js/generated/component-contract-meta.js');
const check = process.argv.includes('--check');

const entries = readdirSync(contractsDir)
  .filter((name) => name.endsWith('.contract.json') && !name.startsWith('_'))
  .map((name) => JSON.parse(readFileSync(join(contractsDir, name), 'utf8')))
  .sort((left, right) => left.id.localeCompare(right.id))
  .map((contract) => [contract.id, {
    id: contract.id,
    status: contract.status,
    intent: contract.intent,
    anatomy: contract.anatomy,
    variants: Object.keys(contract.variants),
    sizes: Object.keys(contract.sizes),
    states: contract.states,
    props: contract.props,
    tokenRefs: contract.tokenRefs,
    accessibility: contract.accessibility,
    keyboardInteractions: contract.keyboardInteractions,
    usagePatterns: contract.usagePatterns,
    responsiveBehavior: contract.responsiveBehavior,
    openQuestions: contract.openQuestions ?? [],
  }]);

const output = `"use strict";\n/* AUTO-GENERATED by scripts/build-component-meta.mjs. */\nconst COMPONENT_CONTRACTS=${JSON.stringify(Object.fromEntries(entries), null, 2)};\n`;

if (check) {
  const current = existsSync(outputPath) ? readFileSync(outputPath, 'utf8') : '';
  if (current !== output) {
    console.error(`${outputPath} is stale. Run: npm run build:component-meta`);
    process.exitCode = 1;
  } else {
    console.log(`${outputPath} is up to date (${entries.length} component contracts).`);
  }
} else {
  writeFileSync(outputPath, output);
  console.log(`Wrote ${outputPath} (${entries.length} component contracts).`);
}
